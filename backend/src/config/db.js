const sp_ApproveApplication = (application_id, approved_by, start_date, end_date, required_hours = 486) => {
  const app = applications.find(a => a.application_id === parseInt(application_id));
  if (!app) return null;

  app.status = "accepted";
  app.approved_by = parseInt(approved_by);
  app.approved_at = new Date().toISOString();

  // Create placement
  const new_placement_id = ojt_placements.length + 1;
  const placement = {
    placement_id: new_placement_id,
    student_id: app.student_id,
    company_id: app.company_id,
    start_date: start_date || new Date().toISOString().split('T')[0],
    end_date: end_date || "2026-11-30",
    required_hours: parseInt(required_hours),
    total_hours_rendered: 0.00,
    status: "ongoing"
  };
  ojt_placements.push(placement);

  // Deduct company slots
  const comp = companies.find(c => c.company_id === app.company_id);
  if (comp && comp.slots_available > 0) {
    comp.slots_available -= 1;
  }

  // Notify student
  const student = students.find(s => s.student_id === app.student_id);
  if (student && comp) {
    notifications.push({
      notification_id: notifications.length + 1,
      user_id: student.user_id,
      message: `Your application to ${comp.company_name} has been approved! Placement created.`,
      type: "placement",
      is_read: false,
      created_at: new Date().toISOString()
    });
  }

  return { application: app, placement };
};

const sp_RecordAttendance = (placement_id, log_date, time_in, time_out) => {
  // calculate hours
  const inParts = time_in.split(':').map(Number);
  const outParts = time_out.split(':').map(Number);
  const inMins = inParts[0] * 60 + inParts[1];
  const outMins = outParts[0] * 60 + outParts[1];
  let hours = ((outMins - inMins) / 60.0);
  if (hours < 0) hours += 24;
  hours = parseFloat(hours.toFixed(2));

  const new_att_id = attendance.length + 1;
  const attRecord = {
    attendance_id: new_att_id,
    placement_id: parseInt(placement_id),
    log_date,
    time_in,
    time_out,
    hours_rendered: hours,
    status: "present",
    remarks: "DTR logged"
  };
  attendance.push(attRecord);

  // Update total hours in placement
  const placement = ojt_placements.find(p => p.placement_id === parseInt(placement_id));
  if (placement) {
    placement.total_hours_rendered = parseFloat((placement.total_hours_rendered + hours).toFixed(2));
    sp_CheckAndCompletePlacement(placement.placement_id);
  }

  return attRecord;
};

const sp_GetStudentProgress = (placement_id) => {
  const placement = ojt_placements.find(p => p.placement_id === parseInt(placement_id));
  if (!placement) return null;
  const progress_percent = parseFloat(((placement.total_hours_rendered / placement.required_hours) * 100).toFixed(2));
  return {
    placement_id: placement.placement_id,
    required_hours: placement.required_hours,
    total_hours_rendered: placement.total_hours_rendered,
    progress_percent: Math.min(progress_percent, 100),
    status: placement.status
  };
};

const sp_SubmitEvaluation = (placement_id, evaluator_name, attendance_score, work_quality_score, attitude_score, remarks) => {
  const total = parseFloat(attendance_score) + parseFloat(work_quality_score) + parseFloat(attitude_score);
  const new_eval_id = evaluations.length + 1;
  const evalRecord = {
    evaluation_id: new_eval_id,
    placement_id: parseInt(placement_id),
    evaluator_name,
    attendance_score: parseFloat(attendance_score),
    work_quality_score: parseFloat(work_quality_score),
    attitude_score: parseFloat(attitude_score),
    total_score: parseFloat(total.toFixed(2)),
    remarks,
    evaluated_at: new Date().toISOString()
  };
  evaluations.push(evalRecord);
  return evalRecord;
};

const sp_CheckAndCompletePlacement = (placement_id) => {
  const placement = ojt_placements.find(p => p.placement_id === parseInt(placement_id));
  if (placement && placement.total_hours_rendered >= placement.required_hours) {
    placement.status = "completed";
  }
  return placement;
};

