const sp_RegisterStudent = (email, password_hash, student_number, full_name, course, year_level) => {
  const new_user_id = users.length + 1;
  const newUser = { user_id: new_user_id, email, password_hash, role: "student", status: "pending", created_at: new Date().toISOString() };
  users.push(newUser);

  const new_student_id = students.length + 1;
  const newStudent = { student_id: new_student_id, user_id: new_user_id, student_number, full_name, course, year_level, contact_number: "", address: "", required_hours: 486, profile_photo: null };
  students.push(newStudent);

  return { user: newUser, student: newStudent };
};

const sp_SubmitRequirement = (student_id, requirement_id, file_path) => {
  const new_submission_id = student_requirements.length + 1;
  const newSub = {
    submission_id: new_submission_id,
    student_id: parseInt(student_id),
    requirement_id: parseInt(requirement_id),
    file_path,
    status: "pending",
    remarks: null,
    reviewed_by: null,
    submitted_at: new Date().toISOString(),
    reviewed_at: null
  };
  student_requirements.push(newSub);
  return newSub;
};

const sp_ReviewRequirement = (submission_id, status, remarks, reviewed_by) => {
  const sub = student_requirements.find(s => s.submission_id === parseInt(submission_id));
  if (sub) {
    sub.status = status;
    sub.remarks = remarks;
    sub.reviewed_by = parseInt(reviewed_by);
    sub.reviewed_at = new Date().toISOString();

    // Create notification
    const student = students.find(s => s.student_id === sub.student_id);
    const req = requirement_types.find(r => r.requirement_id === sub.requirement_id);
    if (student && req) {
      notifications.push({
        notification_id: notifications.length + 1,
        user_id: student.user_id,
        message: `Your submission for '${req.name}' has been ${status}. Remarks: ${remarks || 'None'}`,
        type: status === 'approved' ? 'approval' : 'rejection',
        is_read: false,
        created_at: new Date().toISOString()
      });
    }
  }
  return sub;
};

